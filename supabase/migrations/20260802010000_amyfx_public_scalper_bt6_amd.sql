create table if not exists public.amyfx_preview_scalper_candidate_telemetry (
  id bigint generated by default as identity primary key,
  candidate_id text not null,
  engine_version text not null,
  base_config_version text not null,
  repair_config_version text not null,
  driver_id text not null,
  timeframe text not null check (timeframe in ('M15','M30','H1','H4')),
  direction text not null check (direction in ('BUY','SELL')),
  signal_candle_close_time bigint not null,
  accepted boolean not null,
  gate_id text not null,
  failed_conditions text[] not null default '{}',
  features jsonb,
  observed_at timestamptz not null default now(),
  unique (candidate_id, engine_version, base_config_version, repair_config_version)
);

create index if not exists amyfx_preview_scalper_telemetry_driver_time_idx
  on public.amyfx_preview_scalper_candidate_telemetry (driver_id, timeframe, signal_candle_close_time desc);
create index if not exists amyfx_preview_scalper_telemetry_rejected_idx
  on public.amyfx_preview_scalper_candidate_telemetry (gate_id, signal_candle_close_time desc)
  where accepted = false;

alter table public.amyfx_preview_scalper_pattern_configs enable row level security;
alter table public.amyfx_preview_scalper_candidate_telemetry enable row level security;

revoke all on public.amyfx_preview_scalper_pattern_configs from anon, authenticated;
revoke all on public.amyfx_preview_scalper_candidate_telemetry from anon, authenticated;

grant all on public.amyfx_preview_scalper_pattern_configs to service_role;
grant all on public.amyfx_preview_scalper_candidate_telemetry to service_role;
grant usage, select on all sequences in schema public to service_role;
