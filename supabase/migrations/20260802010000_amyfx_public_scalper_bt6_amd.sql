-- Existing amyfx_preview_* table names are retained because the shared Scalper backend already uses them.
-- This migration intentionally excludes the Preview-only news delivery ledger and scheduler routes.

alter table public.amyfx_preview_scalper_setups drop constraint if exists amyfx_preview_scalper_setups_model_check;
alter table public.amyfx_preview_scalper_setups
  add constraint amyfx_preview_scalper_setups_model_check check (model in (
    'IFVG_SCALPER','FVG_BUY_HIGH_QUALITY',
    'FVG','CRT','ORDER_BLOCK','BREAKER_BLOCK','RETEST_BOS',
    'TRENDLINE_BREAK_RETEST','EMA_PULLBACK','FALSE_BREAKOUT','RANGE_EXPANSION','AMD'
  ));

create table if not exists public.amyfx_preview_scalper_pattern_configs (
  config_type text not null check (config_type in ('BASE','REPAIR','AMD')),
  version text not null,
  enabled boolean not null default true,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  primary key (config_type, version)
);

